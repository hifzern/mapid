create schema if not exists extensions;
create extension if not exists postgis with schema extensions;

create schema if not exists private;
revoke all on schema private from public;

create table public.study_area (
  id boolean primary key default true check (id),
  name text not null,
  source text not null,
  geom extensions.geometry(MultiPolygon, 4326) not null,
  constraint study_area_valid_geom check (
    not extensions.st_isempty(geom) and extensions.st_isvalid(geom)
  )
);

create table public.existing_routes (
  id bigint generated by default as identity primary key,
  name text not null,
  route_type text not null check (route_type in ('bus', 'angkot', 'brt', 'other')),
  source text not null,
  geom extensions.geometry(LineString, 4326) not null,
  constraint existing_routes_valid_geom check (
    not extensions.st_isempty(geom) and extensions.st_isvalid(geom)
  )
);

create table public.population_grid (
  id bigint generated by default as identity primary key,
  admin_name text not null,
  population bigint not null check (population >= 0),
  source text not null,
  geom extensions.geometry(MultiPolygon, 4326) not null,
  constraint population_grid_valid_geom check (
    not extensions.st_isempty(geom) and extensions.st_isvalid(geom)
  )
);

create table public.property_go (
  id bigint generated by default as identity primary key,
  kategori text not null,
  jenis text not null check (jenis in ('Sewa', 'Jual')),
  alamat text,
  source text not null,
  geom extensions.geometry(Point, 4326) not null,
  constraint property_go_valid_geom check (
    not extensions.st_isempty(geom) and extensions.st_isvalid(geom)
  )
);

create table public.scoring_config (
  id boolean primary key default true check (id),
  buffer_meters integer not null default 500 check (buffer_meters between 1 and 5000),
  overlap_tolerance_meters integer not null default 100
    check (overlap_tolerance_meters between 1 and 1000),
  population_per_km_target numeric(14, 2) check (population_per_km_target > 0),
  population_weight numeric(4, 3) not null default 0.625
    check (population_weight between 0 and 1),
  overlap_weight numeric(4, 3) not null default 0.375
    check (overlap_weight between 0 and 1),
  constraint scoring_weights_total_one check (population_weight + overlap_weight = 1)
);

insert into public.scoring_config (id) values (true);

create index study_area_geom_idx on public.study_area using gist (geom);
create index existing_routes_geom_idx on public.existing_routes using gist (geom);
create index population_grid_geom_idx on public.population_grid using gist (geom);
create index property_go_geom_idx on public.property_go using gist (geom);

